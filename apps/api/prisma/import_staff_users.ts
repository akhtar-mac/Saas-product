async function importLegacyUsers() {
  console.log(`Starting import of ${LEGACY_USERS.length} legacy users...`);

  let successCount = 0;
  let updateCount = 0;

  for (const user of LEGACY_USERS) {
    let email = user.email.toLowerCase().trim();
    const roleId = OLD_USER_TYPE_TO_ROLE_ID[user.old_user_type] || 7;
    const passwordHash = await bcrypt.hash(user.raw_password, 10);
    const perms = JSON.stringify(ROLE_DEFAULT_PERMS[roleId] || ['dashboard:view']);

    // Check by ID or Email
    const existingById = await prisma.staff_users.findUnique({ where: { id: user.id } });
    const existingByEmail = await prisma.staff_users.findUnique({ where: { email } });

    if (existingById) {
      // Update by ID
      const updated = await prisma.staff_users.update({
        where: { id: user.id },
        data: {
          name: user.name,
          email:
            existingByEmail && existingByEmail.id !== user.id
              ? `${email.split('@')[0]}+${user.id}@${email.split('@')[1]}`
              : email,
          phone: user.phone,
          password_hash: passwordHash,
          role_id: roleId,
          roles: JSON.stringify([roleId]),
          permissions: perms,
          is_active: user.status === 1,
          is_online: user.is_online === 1,
          last_login_at: user.last_login_at ? new Date(user.last_login_at) : null,
          created_by: user.added_by && user.added_by > 0 ? user.added_by : null,
        },
      });

      // Update staff_user_roles entry
      try {
        await (prisma as any).staff_user_roles.upsert({
          where: { user_id_role_id: { user_id: updated.id, role_id: roleId } },
          create: { user_id: updated.id, role_id: roleId, assigned_by: user.added_by || 1 },
          update: {},
        });
      } catch {}

      console.log(
        `Updated user #${updated.id}: ${user.name} (${updated.email}) -> Role ID ${roleId}`
      );
      updateCount++;
    } else if (existingByEmail) {
      // Update by Email
      const updated = await prisma.staff_users.update({
        where: { email },
        data: {
          name: user.name,
          phone: user.phone,
          password_hash: passwordHash,
          role_id: roleId,
          roles: JSON.stringify([roleId]),
          permissions: perms,
          is_active: user.status === 1,
          is_online: user.is_online === 1,
          last_login_at: user.last_login_at ? new Date(user.last_login_at) : null,
          created_by: user.added_by && user.added_by > 0 ? user.added_by : null,
        },
      });

      try {
        await (prisma as any).staff_user_roles.upsert({
          where: { user_id_role_id: { user_id: updated.id, role_id: roleId } },
          create: { user_id: updated.id, role_id: roleId, assigned_by: user.added_by || 1 },
          update: {},
        });
      } catch {}

      console.log(
        `Updated user by email #${updated.id}: ${user.name} (${email}) -> Role ID ${roleId}`
      );
      updateCount++;
    } else {
      // Create new with ID specified
      const created = await prisma.staff_users.create({
        data: {
          id: user.id,
          name: user.name,
          email: email,
          phone: user.phone,
          password_hash: passwordHash,
          role_id: roleId,
          roles: JSON.stringify([roleId]),
          permissions: perms,
          is_active: user.status === 1,
          is_online: user.is_online === 1,
          last_login_at: user.last_login_at ? new Date(user.last_login_at) : null,
          created_by: user.added_by && user.added_by > 0 ? user.added_by : null,
          created_at: user.created_at ? new Date(user.created_at) : new Date(),
          updated_at: user.updated_at ? new Date(user.updated_at) : new Date(),
        },
      });

      try {
        await (prisma as any).staff_user_roles.create({
          data: {
            user_id: created.id,
            role_id: roleId,
            assigned_by: user.added_by || 1,
          },
        });
      } catch {}

      console.log(`Created new user #${created.id}: ${user.name} (${email}) -> Role ID ${roleId}`);
      successCount++;
    }
  }

  console.log(`\nImport Completed Successfully!`);
  console.log(`Created: ${successCount} users`);
  console.log(`Updated: ${updateCount} users`);
}

importLegacyUsers()
  .catch((e) => {
    console.error('Import failed:', e);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
